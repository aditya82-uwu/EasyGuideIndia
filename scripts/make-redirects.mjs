// Build public/_redirects (Cloudflare Pages) from vercel.json, which apply-review.mjs maintains.
// Each old WordPress URL gets a with-slash and a no-slash rule, both permanent.
import { readFile, writeFile } from 'node:fs/promises';

const root = new URL('../', import.meta.url);
const { redirects } = JSON.parse(await readFile(new URL('vercel.json', root), 'utf8'));

const lines = ['# Generated by scripts/make-redirects.mjs from vercel.json. Do not edit by hand.'];
const seen = new Set();
for (const r of redirects) {
  const withSlash = r.source.endsWith('/') ? r.source : r.source + '/';
  const noSlash = withSlash.length > 1 ? withSlash.slice(0, -1) : withSlash;
  for (const src of [withSlash, noSlash]) {
    if (seen.has(src)) continue;
    seen.add(src);
    lines.push(`${src} ${r.destination} 301`);
  }
}
await writeFile(new URL('public/_redirects', root), lines.join('\n') + '\n');
console.log(`${lines.length - 1} rules for ${redirects.length} redirects`);
